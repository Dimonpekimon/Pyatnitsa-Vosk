def _serialized(method):
    """Один исполнитель для голоса, HTTP и Telegram; допускает вложенный handle/process."""
    @wraps(method)
    def wrapped(self, *args, **kwargs):
        with self._command_lock:
            return method(self, *args, **kwargs)
    return wrapped


class Pyatnitsa:
    """Голосовой ассистент."""

