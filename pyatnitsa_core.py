    # ==================================================================
    #  Сопоставление команд
    # ==================================================================
    @staticmethod
    def _build_alias_index() -> list:
        """Все синонимы с их основами, отсортированные от длинных к коротким.

        Основа считается один раз при сборке индекса: в горячем пути
        сопоставления остаётся только сравнение строк.
        """
        pairs = []
        for intent in INTENTS:
            for alias in intent.aliases:
                normalized = normalize_command_text(alias)
                stems = tuple(stem_ru(word) for word in normalized.split()
                              if word not in _STEM_FILLERS)
                pairs.append((normalized, stems, intent))
        pairs.sort(key=lambda item: len(item[0]), reverse=True)
        return pairs

    @staticmethod
    def _score(text: str, alias: str):
        """Оценка совпадения фразы с синонимом. None — не совпало.

        Чем точнее и длиннее совпадение, тем выше балл. Именно это исправляет
        прежнюю ошибку, когда «выключи компьютер» попадало в команду громкости.
        """
        if not alias:
            return None
        if text == alias:
            return 10000 + len(alias) * 10
        # Прощания-однословки совпадают только целиком. Иначе «я хочу спать»
        # и «пока не знаю» выключали ассистента посреди обычной фразы.
        if alias in WEAK_FAREWELLS:
            return None
        if contains_word(text, alias):
            return 5000 + len(alias) * 10
        if len(alias) >= 5 and alias in text:
            return 1000 + len(alias) * 10
        return None

    #: Синоним короче этого по основам не сравниваем: «пока» и «спать» слишком
    #: легко совпадают с посторонними словами.
    _STEM_MIN_ALIAS = 6

    @classmethod
    def _stem_score(cls, word_stems, alias: str, stems) -> "int | None":
        """Совпадение с точностью до падежа и окончания. None — не совпало.

        Распознавание речи отдаёт фразу в произнесённой форме: «закрой окна»,
        «выключи интерфейса», «прибавь громкости». Реестр хранит один вид, и
        раньше такие фразы уходили нейросети — со стороны это выглядело как
        «ассистент не понял простую команду».

        Правило строгое в обе стороны: каждое слово фразы должно объясняться
        этим синонимом (кроме вежливых вставок вроде «пожалуйста»), и каждое
        слово синонима должно найтись во фразе. Поэтому «закрой дверь» не
        станет «закрой окно», «закрой все окна» не станет «закрой окно
        ассистента», а «закрой, пожалуйста, все окна» — станет.
        """
        if len(alias) < cls._STEM_MIN_ALIAS or not stems:
            return None
        matched = set()
        covered = 0
        # Основы слов фразы считает вызывающий: они одни и те же для всех
        # синонимов, а stem_ru — самая дорогая часть сравнения.
        for stem in word_stems:
            hits = [candidate for candidate in stems
                    if stem_matches(stem, candidate)]
            if not hits:
                return None
            covered += 1
            matched.update(hits)
        # Синоним не должен быть «шире» фразы: иначе «закрой окно ассистента»
        # подошёл бы под «закрой окна», а «выключи интерфейс ассистента» —
        # под «выключи интерфейс».
        if not covered or len(matched) != len(set(stems)):
            return None
        # Полное покрытие фразы — не слабее совпадения по границам слов, но
        # проигрывает точной форме: длина синонима остаётся решающей, поэтому
        # «запусти роблокс студию» остаётся Studio, а не Player.
        return 5000 + len(alias) * 10

    #: Предел кэша сопоставлений — защита от роста на случайных фразах.
    _MATCH_CACHE_MAX = 256

    def match_intent(self, text: str):
        """Возвращает (Intent, совпавший_синоним) или (None, None).

        Результат кэшируется: в пределах одной реплики фраза (или её часть)
        сопоставляется несколько раз, а перебор идёт по всем ~1500 синонимам.
        """
        normalized = normalize_command_text(text)
        if not normalized:
            return None, None
        cached = self._match_cache.get(normalized)
        if cached is not None:
            return cached
        best = self._best_match(normalized)
        if best is None and any("a" <= ch <= "z" for ch in normalized):
            # Забыли переключить раскладку: «gjrf» вместо «пока». Переводим и
            # пробуем снова — но только если исходная фраза не совпала ни с
            # чем, иначе английские названия ломались бы («open chrome»).
            switched = normalize_command_text(from_en_layout(normalized))
            if switched and switched != normalized:
                best = self._best_match(switched)
        result = (best[1], best[2]) if best else (None, None)
        if len(self._match_cache) >= self._MATCH_CACHE_MAX:
            self._match_cache.clear()
        self._match_cache[normalized] = result
        return result

    def _best_match(self, normalized: str):
        """Лучшее совпадение для уже нормализованной фразы: (балл, Intent, синоним).

        Балл нужен отдельно от :meth:`match_intent`: по нему разбор составной
        команды отличает уверенное совпадение от случайного.
        """
        word_stems = [stem_ru(word) for word in normalized.split()
                      if word not in _STEM_FILLERS]
        best = None
        for alias, stems, intent in self._alias_index:
            score = self._score(normalized, alias)
            if score is None:
                score = self._stem_score(word_stems, alias, stems)
            if score is None:
                continue
            score += intent.priority
            if best is None or score > best[0]:
                best = (score, intent, alias)
        return best

    # ==================================================================
    #  Обработка фразы
    # ==================================================================
    @_serialized
    def process(self, raw: str) -> str:
        """Обрабатывает фразу и возвращает ответ (без озвучки).

        Понимает составные команды: «сделай громче и напомни через 5 минут позвонить».
        Фраза делится только если КАЖДАЯ часть распознаётся как известная команда —
        иначе она целиком уходит в LLM, чтобы не разорвать обычный вопрос.
        """
        if not raw or not raw.strip():
            return ""
        if not self._running:
            return f"{config.ASSISTANT_NAME} уже выключается, сэр."
        text = self._strip_wake_word(raw.strip())
        if not text:
            # Прозвучало (или напечатано) только обращение — команды нет.
            # Раньше пустая строка уходила в нейросеть, та ругалась «пустой
            # запрос», и человек слышал «не расслышал команду» — как будто
            # сломан микрофон. Отвечаем как на обращение.
            log("Прозвучало только обращение — команды нет.", "info")
            emit_message("user", raw.strip())
            return ResponseBank.get("wake_ack")
        log(f"Вы: {text}", "info")
        emit_message("user", text)
        emit_state("thinking")

        parts = self._split_compound(text)
        if parts:
            log(f"Составная команда: {len(parts)} части.", "debug")
            responses = [self._execute_single(part) for part in parts]
            answer = " ".join(response for response in responses if response)
        else:
            answer = self._execute_single(text)

        self.last_response = answer
        # Если ответ уже озвучивается, состояние «говорит» выставит поток озвучки.
        if not self.speaker.busy:
            emit_state("idle")
        return answer

    def _execute_single(self, text: str) -> str:
        """Выполняет одну команду. Если она не распознана — передаёт вопрос модели."""
        intent, alias = self.match_intent(text)
        if intent is not None:
            handler = getattr(self, intent.handler, None)
            if handler is None:
                log(f"Нет обработчика для «{intent.name}»", "error")
            else:
                self._fill_silence(intent.name)
                try:
                    result = handler(text, alias)
                except Exception as exc:  # noqa: BLE001
                    log(f"Ошибка выполнения «{intent.name}»: {exc}", "error")
                    result = "Сэр, при выполнении команды произошла ошибка."
                if result:
                    return result
                log(f"Команда «{intent.name}» не дала результата — пробую LLM.", "debug")
        return self._ask_llm(text)

    # Разделители составных команд. Длинные варианты обязаны идти первыми,
    # иначе «и» разорвёт фразу раньше, чем «и потом».
    _COMPOUND_SPLIT = re.compile(
        r"\s+(?:и|а)\s+потом\s+|\s+и\s+затем\s+|\s+затем\s+|\s+после\s+этого\s+|\s+и\s+",
        re.IGNORECASE,
    )
    _MAX_COMPOUND_PARTS = 3

    #: Минимальный балл для части составной команды. 5000 — совпадение по
    #: целым словам или по основе; более слабое (1000) означает, что имя
    #: команды просто встретилось внутри другого слова: «выбери между
    #: телеграмом и дискордом» не должно превращаться в две команды.
    _COMPOUND_MIN_SCORE = 5000

    #: Команды, у которых «и» — часть самой фразы, а не разделитель команд:
    #: «выбери между пиццей и суши» делить нельзя, иначе вторая половина
    #: уедет в свою команду (названия программ теперь тоже команды).
    _NO_SPLIT_INTENTS = {"choose"}

    def _split_compound(self, text: str) -> list:
        """Делит фразу на команды, если все части уверенно распознаются."""
        if not self._COMPOUND_SPLIT.search(text):
            return []
        whole = self._best_match(normalize_command_text(text))
        if whole is not None and whole[1].name in self._NO_SPLIT_INTENTS:
            return []
        parts = [part.strip(" ,.;:!?—-") for part in self._COMPOUND_SPLIT.split(text)]
        parts = [part for part in parts if len(part) >= 3]
        if not 2 <= len(parts) <= self._MAX_COMPOUND_PARTS:
            return []
        for part in parts:
            best = self._best_match(normalize_command_text(part))
            if best is None or best[0] < self._COMPOUND_MIN_SCORE:
                return []
        return parts

    # Команды, которые ходят в сеть или распознают экран: между «услышал» и
    # «ответил» проходит заметное время, и молчание выглядит как зависание.
    _SLOW_INTENTS = {"weather", "briefing", "search", "read_screen",
                     "analyze_screen", "convert", "currency", "find_file"}

    def _fill_silence(self, intent_name: str) -> None:
        """Подаёт голос перед долгой командой: «Секунду, сэр...».

        Вызывается из главного потока, а озвучка идёт своим потоком, поэтому
        саму команду отбивка не задерживает. Если ассистент уже говорит
        (например, в составной команде), второй раз не повторяем.
        """
        if not config.THINKING_FILLER or intent_name not in self._SLOW_INTENTS:
            return
        if self.speaker.busy:
            return
        self.speaker.say(ResponseBank.get("thinking"))

    def handle(self, raw: str) -> str:
        """Обрабатывает фразу и озвучивает ответ."""
        response = self.process(raw)
        if response:
            self.speaker.say(response)
        return response

    # Короче этого слово не может быть обращением по нечёткому совпадению:
    # иначе «пятно» (5 букв) снималось бы как «пятница».
    _WAKE_FUZZY_MIN_LEN = 6
    _WAKE_PUNCT = " \t\r\n,.!?-—–…:;\"'()«»"

    @classmethod
    def _strip_wake_word(cls, text: str) -> str:
        """Убирает обращение из фразы — где бы оно ни стояло.

        Раньше снимался только префикс: «слушай, Пятница, который час» целиком
        уходило в нейросеть вместе с окликом, а «который час, Пятница» вообще
        не совпадало с командой. Заодно ловим падежи, которых нет в WAKE_WORDS
        («пятницей», «пятницо»): Vosk слышит окончания вольно.
        """
        if not text:
            return text
        kept: list[str] = []
        removed = False
        for token in text.split():
            bare = token.strip(cls._WAKE_PUNCT).lower().replace("ё", "е")
            if bare and cls._is_wake_token(bare):
                removed = True
                continue
            kept.append(token)
        if not removed:
            return text
        # Запятую от снятого оклика убираем, а «?» в конце вопроса оставляем:
        # он ещё пригодится нейросети.
        result = " ".join(kept).strip()
        return result.lstrip(cls._WAKE_PUNCT).rstrip(" \t\r\n,.—–…:;\"'()«»")

    @classmethod
    def _is_wake_token(cls, bare: str) -> bool:
        """Похоже ли отдельное слово на обращение (слово уже нормализовано)."""
        for wake in config.WAKE_WORDS:
            if bare == wake:
                return True
            # Только длинные основы: «пятниц» -> «пятница», но не «пят».
            if len(bare) >= cls._WAKE_FUZZY_MIN_LEN - 1:
                if bare.startswith(wake) or wake.startswith(bare):
                    return True
        if len(bare) < cls._WAKE_FUZZY_MIN_LEN:
            return False
        import difflib

        for wake in config.WAKE_WORDS:
            if difflib.SequenceMatcher(None, bare, wake).ratio() >= config.WAKE_WORD_CUTOFF:
                return True
        return False

