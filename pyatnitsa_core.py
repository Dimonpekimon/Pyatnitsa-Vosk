    def _h_reminder(self, raw, alias) -> str:
        seconds = parse_duration(raw)
        clock = None
        if seconds is None:
            # Абсолютное время: «напомни в 18:30», «разбуди в семь утра».
            # Раньше такие фразы понимались только как интервал, и ассистент
            # переспрашивал «через какое время», хотя время уже назвали.
            clock = self._extract_clock_time(raw)
            if clock is not None:
                seconds = self._seconds_until(clock)
        text = self._extract_reminder_text(raw, clock=clock)
        if not text:
            # «Разбуди в 7 утра» и «поставь будильник на 6:45» — время названо,
            # а дела нет: для будильника делом считаем сам подъём.
            speech = normalize_text(raw)
            if "разбуд" in speech or "будильник" in speech:
                text = "подъём"
        if not text:
            return "Что именно напомнить, сэр?"
        if seconds is None:
            return f"Через какое время напомнить: «{text}»?"
        return self.scheduler.add_reminder(seconds, text)

    @staticmethod
    def _extract_clock_time(raw: str):
        """Время суток из фразы: «в 18:30», «в 7 утра». None — время не названо."""
        source = (raw or "").lower().replace("ё", "е")
        # Двоеточие проверяем до нормализации: normalize_text его выбрасывает,
        # и «18:30» превратилось бы в «18 30».
        match = re.search(r"\b(\d{1,2})[:.](\d{2})\b", source)
        if match:
            hour, minute = int(match.group(1)), int(match.group(2))
        else:
            match = re.search(
                r"\b(?:в|к|ко|на)\s+(\d{1,2})(?:\s+(утра|дня|вечера|ночи))?\b",
                normalize_text(source))
            if match is None:
                return None
            hour, minute = int(match.group(1)), 0
            part = match.group(2) or ""
            if part in ("вечера", "дня") and hour < 12:
                hour += 12
            elif part in ("утра", "ночи") and hour == 12:
                hour = 0
        if not (0 <= hour <= 23 and 0 <= minute <= 59):
            return None
        return hour, minute

    @staticmethod
    def _seconds_until(clock) -> int:
        """Сколько секунд ждать до ближайшего наступления названного времени."""
        now = datetime.now()
        moment = now.replace(hour=clock[0], minute=clock[1], second=0, microsecond=0)
        if moment <= now:
            moment += timedelta(days=1)
        return max(1, int((moment - now).total_seconds()))

