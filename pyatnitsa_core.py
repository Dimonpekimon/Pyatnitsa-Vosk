    def _extract_reminder_text(self, raw: str, clock=None) -> str:
        source = (raw or "").lower().replace("ё", "е")
        if clock is not None:
            # Названное время вырезаем до нормализации: иначе от «18:30»
            # останутся цифры «18 30» и попадут в текст напоминания.
            # Предлог уходит вместе со временем — иначе в тексте остаётся «в».
            source = re.sub(r"\b(?:в|к|ко|на)\s+\d{1,2}[:.]\d{2}\b", " ", source)
            source = re.sub(r"\b\d{1,2}[:.]\d{2}\b", " ", source)
            source = re.sub(r"\b(?:в|к|ко|на)\s+\d{1,2}"
                            r"(?:\s+(?:утра|дня|вечера|ночи))?\b", " ", source)
        text = normalize_text(source)
        for phrase in ("не забудь напомнить", "напомни мне", "напомни", "напоминание",
                       "будильник", "разбуди", "поставь", "через"):
            text = text.replace(phrase, " ")
        # Убираем указание времени: «10 минут», «полтора часа», «30 секунд».
        text = re.sub(r"\b\d+[.,]?\d*\s*(час\w*|мин\w*|сек\w*)\b", " ", text)
        text = re.sub(r"\b(полчаса|полтора часа)\b", " ", text)
        text = re.sub(r"\b(час\w*|минут\w*|минуту|секунд\w*|секунду)\b", " ", text)
        text = re.sub(r"\b(мне|меня|пожалуйста|сэр|пятниц\w*)\b", " ", text)
        return " ".join(text.split()).strip(" ,.-")

